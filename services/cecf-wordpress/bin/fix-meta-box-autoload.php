<?php

/**
 * wpackagist-plugin/meta-box ships without the plugin's own
 * `vendor/autoload.php`. Meta Box's inc/loader.php checks for that file
 * and, if present, requires it to register the PSR-4 `MetaBox\` namespace
 * (its src/ directory — Integrations, Updater, Abilities). Without it,
 * `new \MetaBox\Integrations\WPML()` in loader.php — called unconditionally,
 * unlike the sibling `\MetaBox\Updater\*` calls a few lines above it, which
 * are correctly guarded with `class_exists()` — throws a fatal Error and
 * WordPress refuses to activate the plugin.
 *
 * This is an upstream packaging gap in the WPackagist mirror (the real
 * wordpress.org SVN release does ship vendor/), not something specific to
 * this project, so rather than pin to an older Meta Box version and lose
 * future fixes/security patches, this regenerates a minimal PSR-4
 * autoloader for `MetaBox\` -> `src/` after every `composer install` /
 * `composer update` (wired up in composer.json's post-install-cmd /
 * post-update-cmd). Safe to re-run; a no-op if the plugin isn't installed.
 */

$pluginDir = __DIR__.'/../web/app/plugins/meta-box';

if (! is_dir($pluginDir)) {
    return;
}

$vendorDir = $pluginDir.'/vendor';

if (! is_dir($vendorDir) && ! mkdir($vendorDir, 0755, true) && ! is_dir($vendorDir)) {
    fwrite(STDERR, "Could not create {$vendorDir}\n");
    exit(1);
}

$autoloader = <<<'PHP'
<?php

// Auto-generated by bin/fix-meta-box-autoload.php on every composer
// install/update — do not edit directly, edit that script instead.
spl_autoload_register(static function (string $class): void {
    if (! str_starts_with($class, 'MetaBox\\')) {
        return;
    }

    $relative = substr($class, strlen('MetaBox\\'));
    $path = __DIR__.'/../src/'.str_replace('\\', '/', $relative).'.php';

    if (is_file($path)) {
        require $path;
    }
});

PHP;

file_put_contents($vendorDir.'/autoload.php', $autoloader);

echo "Patched wpackagist-plugin/meta-box's missing vendor/autoload.php (MetaBox\\ -> src/).\n";
